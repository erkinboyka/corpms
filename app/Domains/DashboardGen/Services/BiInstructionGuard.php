<?php

declare(strict_types=1);

namespace App\Domains\DashboardGen\Services;

/**
 * Отсекает запросы, не относящиеся к корпоративной BI-витрине, до создания
 * дашборда и вызова модели. Позволяет не тратить токены на «погоду в Худжанде»
 * и не оставлять в списке пустые дашборды с ошибкой генерации.
 */
final class BiInstructionGuard
{
    /** @var list<string> */
    private const TOPIC_TERMS = [
        // метрики витрины
        'доход', 'расход', 'выручк', 'прибыл', 'сделк', 'клиент', 'лид', 'воронк', 'конверси',
        'задач', 'счет', 'оплат', 'инвойс', 'штат', 'сотрудник', 'кадр', 'проект', 'склад',
        'запас', 'остатк', 'поставщик', 'закупк', 'посещаемост', 'табель',
        // аналитика и визуализация
        'дашборд', 'метрик', 'витрин', 'график', 'тренд', 'срез', 'kpi', 'отчет',
        'отчёт', 'аналитик', 'analytics', 'сравн', 'период', 'месяц', 'недел', 'квартал',
        'год', 'по дням', 'по неделям', 'по месяцам', 'топ', 'структур',
        // таблицы и домены системы
        'crm', 'finance', 'инвентар', 'бухгалтер', 'налог', 'платеж', 'платёж', 'бюджет',
        'департамент', 'отдел', 'менеджер', 'должност', 'эффективност', 'себестоим', 'марж',
    ];

    private const MIN_LENGTH = 8;

    public function isRelevant(string $instruction): bool
    {
        $text = mb_strtolower(trim($instruction));

        if (mb_strlen($text) < self::MIN_LENGTH) {
            return false;
        }

        if (preg_match('/(?<!\p{L})bi(?!\p{L})/u', $text) === 1) {
            return true;
        }

        foreach (self::TOPIC_TERMS as $term) {
            if (preg_match('/(?<!\p{L})' . preg_quote($term, '/') . '\p{L}*/u', $text) === 1) {
                return true;
            }
        }

        return false;
    }
}
